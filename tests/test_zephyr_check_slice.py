import json
from pathlib import Path

import pytest

from scripts.zephyr_check_slice import (
    MARKER,
    build_slice,
    count_chunks,
    main,
    matches,
    parse_manifest,
)

_CASES = (
    "scripts/zephyr_eval_cases.json",
    "scripts/zephyr_semantic_dev.json",
    "scripts/zephyr_semantic_heldout.json",
)
_MANIFEST = Path("scripts/zephyr_check_slice.txt")


def test_s1_matches_and_parse_manifest():
    assert matches("kernel/a.c", ["kernel/*"])
    assert not matches("kernel/include/a.h", ["kernel/*"])
    assert matches("kernel/include/a.h", ["kernel/**"])
    assert matches("kernel/b.c", ["kernel/*", "!kernel/b.c", "kernel/b.c"])
    text = "# comment\n\nkernel/*\n# another\n"
    assert parse_manifest(text) == ["kernel/*"]


def test_s2_build_slice_copies_matches_and_skips_git(tmp_path: Path):
    src = tmp_path / "src"
    (src / "kernel").mkdir(parents=True)
    (src / "include" / "zephyr").mkdir(parents=True)
    (src / "drivers").mkdir()
    (src / "kernel" / "a.c").write_text("int a;\n", encoding="utf-8")
    (src / "include" / "zephyr" / "x.h").write_text("int x;\n", encoding="utf-8")
    (src / "drivers" / "d.c").write_text("int d;\n", encoding="utf-8")
    (src / ".git").mkdir()
    (src / ".git" / "HEAD").write_text("ref: refs/heads/main\n", encoding="utf-8")
    (src / ".git" / "a.c").write_text("nope\n", encoding="utf-8")

    copied = build_slice(src, tmp_path / "dest", ["kernel/*", "include/**"])
    assert copied == ["include/zephyr/x.h", "kernel/a.c"]
    dest = tmp_path / "dest"
    for rel in copied:
        assert (dest / rel).read_text(encoding="utf-8") == (src / rel).read_text(encoding="utf-8")
    assert (dest / MARKER).read_text(encoding="utf-8") == (
        "generated by scripts/zephyr_check_slice.py\n"
    )
    present = sorted(path.relative_to(dest).as_posix() for path in dest.rglob("*") if path.is_file())
    assert present == [MARKER, "include/zephyr/x.h", "kernel/a.c"]


def test_s3_unused_rule_copies_nothing(tmp_path: Path):
    src = tmp_path / "src"
    src.mkdir()
    (src / "a.c").write_text("int a;\n", encoding="utf-8")
    manifest = tmp_path / "manifest.txt"
    manifest.write_text("*.c\nmissing.h\n", encoding="utf-8")
    dest = tmp_path / "dest"
    with pytest.raises(SystemExit) as raised:
        main(["--src", str(src), "--dest", str(dest), "--manifest", str(manifest)])
    assert "missing.h" in str(raised.value)
    assert not dest.exists()


def test_s4_dest_guard_and_rebuild(tmp_path: Path):
    src = tmp_path / "src"
    src.mkdir()
    (src / "a.c").write_text("int a;\n", encoding="utf-8")
    dest = tmp_path / "dest"
    dest.mkdir()
    (dest / "keep.txt").write_text("stay\n", encoding="utf-8")
    with pytest.raises(SystemExit) as raised:
        build_slice(src, dest, ["*.c"])
    assert "not a check slice" in str(raised.value)
    assert (dest / "keep.txt").read_text(encoding="utf-8") == "stay\n"
    assert not (dest / "a.c").exists()

    (dest / MARKER).write_text("old\n", encoding="utf-8")
    (dest / "stale.c").write_text("stale\n", encoding="utf-8")
    copied = build_slice(src, dest, ["*.c"])
    assert copied == ["a.c"]
    assert (dest / "a.c").read_text(encoding="utf-8") == "int a;\n"
    assert not (dest / "stale.c").exists()
    assert not (dest / "keep.txt").exists()
    assert (dest / MARKER).is_file()


def test_s5_chunk_guard(tmp_path: Path, capsys: pytest.CaptureFixture[str]):
    src = tmp_path / "src"
    src.mkdir()
    (src / "a.c").write_text("int a(void) { return 1; }\n", encoding="utf-8")
    (src / "b.c").write_text("int b(void) { return 2; }\n", encoding="utf-8")
    manifest = tmp_path / "manifest.txt"
    manifest.write_text("*.c\n", encoding="utf-8")
    dest = tmp_path / "dest"
    build_slice(src, dest, ["*.c"])
    loaded, unique = count_chunks(dest)
    assert (loaded, unique)[0] == 2
    assert unique > 1

    with pytest.raises(SystemExit) as raised:
        main(
            [
                "--src",
                str(src),
                "--dest",
                str(dest),
                "--manifest",
                str(manifest),
                "--max-chunks",
                "1",
            ]
        )
    assert str(raised.value).startswith("refusing:")
    capsys.readouterr()

    main(["--src", str(src), "--dest", str(dest), "--manifest", str(manifest)])
    out = capsys.readouterr().out
    assert (
        f"{dest}: 2 files copied, 2 loaded, {unique} unique chunks (limit 1500)"
        in out
    )


def test_s6_expected_paths_match_the_manifest():
    rules = parse_manifest(_MANIFEST.read_text(encoding="utf-8"))
    for name in _CASES:
        cases = json.loads(Path(name).read_text(encoding="utf-8"))
        for case in cases:
            for path in case["expected"]:
                assert matches(path, rules), path


def test_s7_rules_are_relative():
    rules = parse_manifest(_MANIFEST.read_text(encoding="utf-8"))
    assert rules
    for rule in rules:
        assert not rule.startswith("/")
        assert ".." not in rule
