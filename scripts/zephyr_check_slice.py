import argparse
import shutil
import sys
from collections.abc import Sequence
from pathlib import Path, PurePosixPath

# This file lives in scripts/, so that directory is sys.path[0]. The repo root
# has to be importable for `uv run python scripts/zephyr_check_slice.py`.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.chunker import chunk_index, unique_texts
from app.code_index import build_index
from app.config import DEFAULT_EXCLUDE_DIRS
from app.project_loader import load_project_files

MARKER = ".zephyr-check-slice"
DEFAULT_MANIFEST = Path(__file__).resolve().parent / "zephyr_check_slice.txt"


def parse_manifest(text: str) -> list[str]:
    rules = [line.strip() for line in text.splitlines()]
    return [rule for rule in rules if rule and not rule.startswith("#")]


def _matches_rule(rel: str, rule: str) -> bool:
    return PurePosixPath(rel).full_match(rule.removeprefix("!"))


def matches(rel: str, rules: Sequence[str]) -> bool:
    keep = False
    for rule in rules:
        if _matches_rule(rel, rule):
            keep = not rule.startswith("!")
    return keep


def unused_rules(rel_paths: Sequence[str], rules: Sequence[str]) -> list[str]:
    return [r for r in rules if not any(_matches_rule(p, r) for p in rel_paths)]


def list_files(root: Path) -> list[str]:
    return sorted(
        p.relative_to(root).as_posix()
        for p in root.rglob("*")
        if p.is_file() and ".git" not in p.relative_to(root).parts[:1]
    )


def build_slice(src: Path, dest: Path, rules: Sequence[str]) -> list[str]:
    if dest.exists() and any(dest.iterdir()):
        if not (dest / MARKER).is_file():
            raise SystemExit(f"{dest} exists and is not a check slice; remove it or pick another --dest")
        shutil.rmtree(dest)
    copied = [rel for rel in list_files(src) if matches(rel, rules)]
    for rel in copied:
        target = dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src / rel, target)
    dest.mkdir(parents=True, exist_ok=True)
    (dest / MARKER).write_text("generated by scripts/zephyr_check_slice.py\n", encoding="utf-8")
    return copied


def count_chunks(root: Path) -> tuple[int, int]:
    files = load_project_files(root, DEFAULT_EXCLUDE_DIRS)
    chunks = chunk_index(build_index(files), files)
    return len(files), len(unique_texts(chunks))


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Copy the Zephyr check slice.")
    parser.add_argument("--src", default="zephyr-core")
    parser.add_argument("--dest", default="zephyr-core-check")
    parser.add_argument("--manifest", default=str(DEFAULT_MANIFEST))
    parser.add_argument("--max-chunks", type=int, default=1500)
    args = parser.parse_args(argv)
    src, dest = Path(args.src), Path(args.dest)
    if not src.is_dir():
        raise SystemExit(f"{src} not found; run scripts/fetch_zephyr_core.py first")
    rules = parse_manifest(Path(args.manifest).read_text(encoding="utf-8"))
    unused = unused_rules(list_files(src), rules)
    if unused:
        raise SystemExit("rules matching no file: " + ", ".join(unused))
    copied = build_slice(src, dest, rules)
    loaded, unique = count_chunks(dest)
    print(f"{dest}: {len(copied)} files copied, {loaded} loaded, {unique} unique chunks (limit {args.max_chunks})")
    if unique > args.max_chunks:
        raise SystemExit(f"refusing: {unique} unique chunks (max {args.max_chunks})")


if __name__ == "__main__":
    main()
